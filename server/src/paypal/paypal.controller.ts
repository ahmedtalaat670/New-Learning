import {
  Controller,
  Post,
  Body,
  HttpCode,
  HttpStatus,
  Param,
  ParseIntPipe,
} from '@nestjs/common';
import { PaypalService } from './providers/paypal.service';
import { CapturePaypalOrderDto } from './dtos/capture-paypal-order.dto';
import { type PaypalWebhookPayload } from './interfaces/paypal-webhook-payload.interface';
import {
  ApiBearerAuth,
  ApiBody,
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger';

@ApiTags('Payment (PayPal)')
@Controller('paypal')
export class PaypalController {
  constructor(private readonly paypalService: PaypalService) {}

  @Post('create-order/:orderId')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({
    summary: 'Initialize a PayPal order payment link',
    description:
      'Generates a payment order token signature within PayPal matching an internal system order reference ID.',
  })
  @ApiParam({
    name: 'orderId',
    type: Number,
    description:
      'The unique numeric tracking ID of your internal internal shop database order',
  })
  @ApiResponse({
    status: 200,
    description:
      'PayPal execution parameters and approval links constructed successfully.',
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or malformed authorization context token.',
  })
  @ApiResponse({
    status: 404,
    description:
      'Internal application database order configuration matching this orderId not found.',
  })
  public async createOrder(@Param('orderId', ParseIntPipe) orderId: number) {
    return this.paypalService.createPaypalOrder(orderId);
  }

  @Post('capture-order')
  @HttpCode(HttpStatus.OK)
  @ApiBearerAuth()
  @ApiOperation({
    summary: 'Capture an approved PayPal checkout execution context',
    description:
      'Finalizes the transaction payment execution pipeline after the student client confirms approval inside the PayPal screen.',
  })
  @ApiBody({ type: CapturePaypalOrderDto })
  @ApiResponse({
    status: 200,
    description:
      'Funds authorized and captured cleanly. Internal course enrollment triggered simultaneously.',
  })
  @ApiResponse({
    status: 400,
    description:
      'PayPal endpoint rejected execution instructions (e.g., expired token, instrumentation issues).',
  })
  @ApiResponse({
    status: 401,
    description: 'Missing or malformed authorization token context.',
  })
  public async captureOrder(@Body() dto: CapturePaypalOrderDto) {
    return this.paypalService.capturePaypalOrder(dto);
  }

  @Post('webhook')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Asynchronous event handler hook for PayPal webhooks',
    description:
      'Public unauthenticated callback listener used exclusively by PayPal edge servers to broadcast external transaction events (like automated payment capturing confirmation).',
  })
  @ApiBody({
    description:
      'Raw web-hook event payload delivered from the PayPal transaction processing engine',
    schema: {
      type: 'object',
      required: ['event_type', 'resource'],
      properties: {
        event_type: {
          type: 'string',
          example: 'PAYMENT.CAPTURE.COMPLETED',
          description:
            'The type of webhook event notification triggered by PayPal',
        },
        resource: {
          type: 'object',
          required: ['id'],
          description: 'The underlying transaction resource snapshot data',
          properties: {
            id: {
              type: 'string',
              example: '6IX20614Y6473921M',
              description: 'The transaction or capture ID generated by PayPal',
            },
            purchase_units: {
              type: 'array',
              description: 'Optional breakdown of purchase transactional items',
              items: {
                type: 'object',
                properties: {
                  reference_id: {
                    type: 'string',
                    example: 'ORDER-9923A',
                    description:
                      'Your internal system tracking or order reference ID string',
                  },
                },
              },
            },
          },
        },
      },
    },
  })
  @ApiResponse({
    status: 200,
    description:
      'Event received tracking flag signature returned instantly to verify receipt listener state.',
  })
  handlePaypalWebhook(@Body() webhookBody: PaypalWebhookPayload) {
    this.paypalService.handleWebhookApproval(webhookBody).catch(() => {});

    return { received: true };
  }
}
